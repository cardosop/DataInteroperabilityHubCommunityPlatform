class TestIdPMetadataContract:
    def test_valid_document_returns_all_endpoints(self, discovery):
        document = fetch_idp_metadata(discovery.url)
        assert document["issuer"] == GOOD_DOCUMENT["issuer"]
        assert document["jwks_uri"] == GOOD_DOCUMENT["jwks_uri"]

    def test_non_200_reports_the_status_class(self, discovery):
        discovery.status = 503
        with pytest.raises(IdPMetadataError) as exc_info:
            fetch_idp_metadata(discovery.url)
        assert "HTTP 503" in str(exc_info.value)

    def test_missing_jwks_uri_names_the_key(self, discovery):
        payload = dict(GOOD_DOCUMENT)
        payload.pop("jwks_uri")
        discovery.payload = payload
        with pytest.raises(IdPMetadataError) as exc_info:
            fetch_idp_metadata(discovery.url)
        assert "jwks_uri" in str(exc_info.value)

    def test_invalid_json_is_classified(self, discovery):
        # A VERBATIM malformed body (json.dumps("not json") would be a
        # valid JSON string — the wire must carry broken JSON).
        discovery.raw_body = b"{not-json"
        with pytest.raises(IdPMetadataError) as exc_info:
            fetch_idp_metadata(discovery.url)
        assert "not valid JSON" in str(exc_info.value)

    def test_non_object_document_is_classified(self, discovery):
        discovery.payload = ["a", "list"]
        with pytest.raises(IdPMetadataError) as exc_info:
            fetch_idp_metadata(discovery.url)
        assert "not a JSON object" in str(exc_info.value)

    def test_unreachable_host_reports_the_transport_class(self):
        with pytest.raises(IdPMetadataError) as exc_info:
            fetch_idp_metadata(
                "http://127.0.0.1:1/oidc/.well-known/oauth-authorization-server"
            )
        assert "ConnectError" in str(exc_info.value)

    def test_errors_never_carry_the_response_body(self, discovery):
        # A body containing credential-shaped text must never leak
        # through the classified failure.
        discovery.status = 401
        discovery.payload = {"error": "secret-token-value-abc123"}
        with pytest.raises(IdPMetadataError) as exc_info:
            fetch_idp_metadata(discovery.url)
        assert "secret-token-value-abc123" not in str(exc_info.value)


