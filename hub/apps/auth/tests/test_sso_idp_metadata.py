def _b64u(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _generated_ec_jwk() -> dict:
    """A REAL P-256 key generated by cryptography (the EC capability branch)."""
    from cryptography.hazmat.primitives.asymmetric import ec

    key = ec.generate_private_key(ec.SECP256R1())
    numbers = key.private_numbers().public_numbers
    return {
        "alg": "ES256",
        "crv": "P-256",
        "kid": "generated-ec-p256",
        "kty": "EC",
        "use": "sig",
        "x": _b64u(numbers.x.to_bytes(32, "big")),
        "y": _b64u(numbers.y.to_bytes(32, "big")),
    }


class _DiscoveryHandler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        holder = self.server.server_holder
        # The discovery document points its jwks_uri at this same server
        # (the /jwks.json route) so both legs of the capability check run
        # over real TCP against one scripted IdP surface.
        if "/jwks.json" in self.path:
            status = holder.jwks_status
            payload = holder.jwks_payload
            raw_body = holder.jwks_raw_body
        else:
            status = holder.status
            payload = holder.payload
            raw_body = holder.raw_body
        # raw_body (bytes) is sent VERBATIM — a real malformed-JSON body;
        # payload (a JSON-serialisable value) is encoded by the server.
        body = raw_body if raw_body is not None else json.dumps(payload).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *args):  # silence request logging
        pass


class _Discovery:
    def __init__(
        self,
        status=200,
        payload=GOOD_DOCUMENT,
        raw_body=None,
        jwks_status=200,
        jwks_payload=None,
        jwks_raw_body=None,
    ):
        self.status = status
        self.payload = payload
        self.raw_body = raw_body
        self.jwks_status = jwks_status
        self.jwks_payload = (
            jwks_payload if jwks_payload is not None else REAL_DATABRICKS_JWKS
        )
        self.jwks_raw_body = jwks_raw_body
        self.server = http.server.ThreadingHTTPServer(
            ("127.0.0.1", 0), _DiscoveryHandler
        )
        self.server.server_holder = self
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    @property
    def base(self):
        return f"http://127.0.0.1:{self.server.server_address[1]}"

    @property
    def url(self):
        return f"{self.base}/oidc/.well-known/oauth-authorization-server"

    @property
    def jwks_url(self):
        return f"{self.base}/oidc/jwks.json"

    def document_with_local_jwks(self, **overrides) -> dict:
        """The discovery document with its jwks_uri pointed at this server."""
        document = dict(GOOD_DOCUMENT)
        document["jwks_uri"] = self.jwks_url
        document.update(overrides)
        return document

    def close(self):
        self.server.shutdown()


