@override_settings(AUTH_SSO_RATE_LIMIT="10/min")
class SSOCallbackThrottleTest(TestCase):
    """W1.5 — the SSO endpoints are throttled per IP (11th callback 429s)."""

    def setUp(self):
        uid = uuid.uuid4().hex[:8]
        self.tenant = Tenant.objects.create(
            name=f"SSO Throttle {uid}",
            slug=f"sso-throttle-{uid}",
            status="ACTIVE",
            kyc_status="UNVERIFIED",
        )
        self.private, self.public = _generated_rsa_keypair()
        self.idp = _ScriptedIdP({"keys": [self.public]})
        TenantConfig.objects.create(
            tenant=self.tenant,
            sso_config={
                "oidc": {
                    "authorization_endpoint": f"{self.idp.base}/oidc/v1/authorize",
                    "client_id": "test-client-id",
                    "issuer": f"{self.idp.base}/oidc",
                    "jwks_uri": self.idp.jwks_uri,
                }
            },
        )
        cache.clear()

    def tearDown(self):
        self.idp.close()

    def test_eleventh_callback_is_throttled(self):
        client = APIClient()
        state = sso_state.issue_state(str(self.tenant.id), "private")
        now = int(time.time())
        token = pyjwt.encode(
            {
                "iss": f"{self.idp.base}/oidc",
                "aud": "test-client-id",
                "sub": "sub",
                "email": f"throttle-{uuid.uuid4().hex[:8]}@example.com",
                "exp": now + 300,
                "iat": now,
            },
            key=self.private,
            algorithm="RS256",
            headers={"kid": "scripted-idp-key"},
        )
        for i in range(10):
            response = client.post(
                "/api/v1/auth/sso/oidc/callback/",
                {"id_token": token, "state": sso_state.issue_state(str(self.tenant.id), "private")},
                format="json",
            )
            self.assertEqual(
                response.status_code,
                status.HTTP_200_OK,
                f"callback #{i} must succeed within the rate",
            )
        response = client.post(
            "/api/v1/auth/sso/oidc/callback/",
            {"id_token": token, "state": state},
            format="json",
        )
        self.assertEqual(response.status_code, status.HTTP_429_TOO_MANY_REQUESTS)
        self.assertEqual(response.data["error"]["code"], "RATE_LIMIT_EXCEEDED")
