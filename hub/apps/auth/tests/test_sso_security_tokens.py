def _b64u(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _b64decode_for(data: str) -> bytes:
    return base64.urlsafe_b64decode(data + "=" * (-len(data) % 4))


def _generated_rsa_keypair():
    """A REAL 2048-bit RSA keypair generated by cryptography."""
    from cryptography.hazmat.primitives.asymmetric import rsa

    private_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    numbers = private_key.private_numbers().public_numbers
    public_jwk = {
        "alg": "RS256",
        "e": _b64u(numbers.e.to_bytes(3, "big")),
        "kid": "scripted-idp-key",
        "kty": "RSA",
        "n": _b64u(numbers.n.to_bytes(256, "big")),
        "use": "sig",
    }
    from cryptography.hazmat.primitives import serialization

    private_pem = private_key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )
    return private_pem, public_jwk


class _ScriptedIdP:
    """A real HTTP server scripting the discovery + JWKS surface."""

    def __init__(self, jwks):
        self.jwks = jwks
        self.server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), _Handler)
        self.server.server_holder = self
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    @property
    def base(self):
        return f"http://127.0.0.1:{self.server.server_address[1]}"

    @property
    def discovery_url(self):
        return f"{self.base}/oidc/.well-known/oauth-authorization-server"

    @property
    def jwks_uri(self):
        return f"{self.base}/oidc/jwks.json"

    def close(self):
        self.server.shutdown()


class _Handler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        holder = self.server.server_holder
        if "/jwks.json" in self.path:
            body = json.dumps(holder.jwks).encode()
        else:
            document = {
                "issuer": f"http://127.0.0.1:{self.server.server_address[1]}/oidc",
                "authorization_endpoint": (
                    f"http://127.0.0.1:{self.server.server_address[1]}/oidc/v1/authorize"
                ),
                "token_endpoint": f"http://127.0.0.1:{self.server.server_address[1]}/oidc/v1/token",
                "jwks_uri": (
                    f"http://127.0.0.1:{self.server.server_address[1]}/oidc/jwks.json"
                ),
            }
            body = json.dumps(document).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *args):  # silence request logging
        pass


class OIDCCallbackSecurityTest(TestCase):
    """The adversarial matrix against the real callback view."""

    def setUp(self):
        self._private, self._public = _generated_rsa_keypair()
        self._idp = _ScriptedIdP({"keys": [self._public]})
        uid = uuid.uuid4().hex[:8]
        self.tenant = Tenant.objects.create(
            name=f"SSO Tenant {uid}",
            slug=f"sso-tenant-{uid}",
            status="ACTIVE",
            kyc_status="UNVERIFIED",
        )
        self.issuer = f"{self._idp.base}/oidc"
        self.client_id = "test-client-id"
        TenantConfig.objects.create(
            tenant=self.tenant,
            sso_config={
                "oidc": {
                    "authorization_endpoint": f"{self._idp.base}/oidc/v1/authorize",
                    "client_id": self.client_id,
                    "issuer": self.issuer,
                    "jwks_uri": self._idp.jwks_uri,
                }
            },
        )

    def tearDown(self):
        self._idp.close()

    def _token(self, **overrides):
        now = int(time.time())
        claims = {
            "iss": self.issuer,
            "aud": self.client_id,
            "sub": f"sub-{uuid.uuid4().hex[:8]}",
            "email": f"sso-{uuid.uuid4().hex[:8]}@example.com",
            "exp": now + 300,
            "iat": now,
        }
        claims.update(overrides)
        return pyjwt.encode(
            claims, self._private, algorithm="RS256", headers={"kid": "scripted-idp-key"}
        )

    def _callback(self, id_token, state=None, **extra):
        client = APIClient()
        payload = {"id_token": id_token, "state": state or self._issue_state()}
        payload.update(extra)
        return client.post("/api/v1/auth/sso/oidc/callback/", payload, format="json")

    def _issue_state(self, tenant_id=None):
        return sso_state.issue_state(
            str(tenant_id or self.tenant.id), "private"  # APIClient REMOTE_ADDR is loopback
        )

    # ── the valid path ──────────────────────────────────────────────────

    def test_valid_token_authenticates_and_creates_user(self):
        email = f"valid-{uuid.uuid4().hex[:8]}@example.com"
        token = self._token(email=email)
        response = self._callback(token)
        self.assertEqual(response.status_code, status.HTTP_200_OK)
        self.assertIn("access_token", response.data)
        self.assertEqual(response.data["user"]["email"], email)
        user = User.objects.get(email=email)
        self.assertEqual(user.tenant_id, self.tenant.id)

    # ── forged / unsigned / alg-confusion ───────────────────────────────

    def test_forged_garbage_token_400s_and_creates_no_user(self):
        response = self._callback("not-a-jwt.garbage.token")
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)
        self.assertIn("OIDC_TOKEN_SIGNATURE_INVALID", str(response.data))
        self.assertFalse(User.objects.filter(email__startswith="sso-").exists())

    def test_alg_none_token_400s(self):
        now = int(time.time())
        unsigned = pyjwt.encode(
            {
                "iss": self.issuer,
                "aud": self.client_id,
                "sub": "attacker",
                "email": f"none-{uuid.uuid4().hex[:8]}@example.com",
                "exp": now + 300,
            },
            key=None,
            algorithm="none",
        )
        response = self._callback(unsigned)
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)

    def test_hs256_confusion_token_400s(self):
        # alg confusion: the token is HS256-signed with the IdP's PUBLIC
        # key PEM as the HMAC secret (the classic RS256→HS256 attack) —
        # must never be accepted. PyJWT 2.12 refuses to CRAFT such a
        # token, so it is built RAW — exactly what a real attacker does.
        import hashlib
        import hmac
        import json

        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric import rsa

        n = int.from_bytes(_b64decode_for(self._public["n"]), "big")
        e = int.from_bytes(_b64decode_for(self._public["e"]), "big")
        public_pem = (
            rsa.RSAPublicNumbers(e, n)
            .public_key()
            .public_bytes(
                serialization.Encoding.PEM,
                serialization.PublicFormat.SubjectPublicKeyInfo,
            )
        )
        now = int(time.time())
        header = {"alg": "HS256", "typ": "JWT"}
        payload = {
            "iss": self.issuer,
            "aud": self.client_id,
            "sub": "attacker",
            "email": f"hs-{uuid.uuid4().hex[:8]}@example.com",
            "exp": now + 300,
            "iat": now,
        }
        segments = [
            _b64u(json.dumps(header, separators=(",", ":")).encode()),
            _b64u(json.dumps(payload, separators=(",", ":")).encode()),
        ]
        signing_input = ".".join(segments).encode()
        signature = hmac.new(public_pem, signing_input, hashlib.sha256).digest()
        confused = ".".join(segments) + "." + _b64u(signature)

        response = self._callback(confused)
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)

    def test_unknown_kid_token_400s(self):
        other_private, _other_public = _generated_rsa_keypair()
        now = int(time.time())
