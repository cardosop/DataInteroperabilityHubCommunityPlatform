"""
Contract tests for scripts/check_idp_jwks.py (oss-release-remediation W1.0).

The CLI is the LIVE capability check behind the D4 precondition: it
resolves the pilot IdP discovery URL, fetches the real discovery + JWKS
documents over HTTPS, and reports CAPABLE / NOT_CAPABLE / SKIP with
classified reasons.

No mocks: a real stdlib HTTP server scripts the IdP surface (discovery +
JWKS routes over real TCP, the same pattern as
hub/apps/auth/tests/test_sso_idp_metadata.py) and the real httpx client
fetches it; the served key is a REAL RSA key generated by cryptography.

Pins:
- URL resolution priority (--discovery-url > SSO_IDP_DISCOVERY_URL >
  DATABRICKS_PILOT_HOST > DATABRICKS_HOST);
- exit codes: CAPABLE=0, NOT_CAPABLE/failure=1, SKIP=0 (advisory) and 1
  under --strict;
- the W16 policy: CI + no IdP wired raises EnvironmentFailureError
  (fails loudly) instead of skipping;
- --json machine shape;
- --redact-host (the C1 evidence-capture mode — the pilot hostname never
  reaches the output);
- failures never leak response bodies;
- the Makefile wiring (the `check-idp-jwks` target).
"""

import base64
import http.server
import importlib.util
import json
import re
import sys
import threading
from pathlib import Path

import pytest

scripts_dir = Path(__file__).parent.parent
ROOT = scripts_dir.parent
sys.path.insert(0, str(scripts_dir))
sys.path.insert(0, str(ROOT))  # envpolicy + hub live at the repo root

from envpolicy import EnvironmentFailureError

script_path = scripts_dir / "check_idp_jwks.py"
spec = importlib.util.spec_from_file_location("check_idp_jwks", script_path)
check_idp_jwks = importlib.util.module_from_spec(spec)
spec.loader.exec_module(check_idp_jwks)

MAKEFILE = ROOT / "Makefile"


def _b64u(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _generated_rsa_jwk(kid: str = "cli-test-rsa") -> dict:
    """A REAL 2048-bit RSA key generated by cryptography."""
    from cryptography.hazmat.primitives.asymmetric import rsa

    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    numbers = key.private_numbers().public_numbers
    return {
        "alg": "RS256",
        "e": _b64u(numbers.e.to_bytes(3, "big")),
        "kid": kid,
        "kty": "RSA",
        "n": _b64u(numbers.n.to_bytes(256, "big")),
        "use": "sig",
    }


class _ScriptedIdP:
    """A real HTTP server scripting the discovery + JWKS surface."""

    def __init__(self, jwks=None, jwks_status=200, jwks_raw_body=None):
        self.jwks = jwks if jwks is not None else {"keys": [_generated_rsa_jwk()]}
        self.jwks_status = jwks_status
        self.jwks_raw_body = jwks_raw_body
        self.server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), _Handler)
        self.server.server_holder = self
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    @property
    def discovery_url(self):
        port = self.server.server_address[1]
        return f"http://127.0.0.1:{port}/oidc/.well-known/oauth-authorization-server"

    def close(self):
        self.server.shutdown()


class _Handler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        holder = self.server.server_holder
        if "/jwks.json" in self.path:
            status, body = holder.jwks_status, (
                holder.jwks_raw_body
                if holder.jwks_raw_body is not None
                else json.dumps(holder.jwks).encode()
            )
        else:
            document = {
                "issuer": "https://idp.example.com/oidc",
                "authorization_endpoint": "https://idp.example.com/oidc/v1/authorize",
                "token_endpoint": "https://idp.example.com/oidc/v1/token",
                "jwks_uri": f"http://127.0.0.1:{self.server.server_address[1]}/oidc/jwks.json",
            }
            status, body = 200, json.dumps(document).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *args):  # silence request logging
        pass


@pytest.fixture
def idp():
    server = _ScriptedIdP()
    yield server
    server.close()


def _run(*argv):
    monkeypatch = pytest.MonkeyPatch()
    monkeypatch.setattr(sys, "argv", ["check_idp_jwks.py", *argv])
    try:
        with pytest.raises(SystemExit) as exc_info:
            check_idp_jwks.main()
        return exc_info.value.code
    finally:
        monkeypatch.undo()


class TestResolveDiscoveryUrl:
    def test_explicit_argument_wins(self, monkeypatch):
        monkeypatch.setenv("SSO_IDP_DISCOVERY_URL", "https://env.example.com/disc")
        url = check_idp_jwks.resolve_discovery_url("https://arg.example.com/disc")
        assert url == "https://arg.example.com/disc"

    def test_env_var_wins_over_host_vars(self, monkeypatch):
        monkeypatch.setenv("SSO_IDP_DISCOVERY_URL", "https://env.example.com/disc")
        monkeypatch.setenv("DATABRICKS_PILOT_HOST", "pilot.example.com")
        monkeypatch.setenv("DATABRICKS_HOST", "other.example.com")
        assert check_idp_jwks.resolve_discovery_url() == "https://env.example.com/disc"

    def test_pilot_host_preferred_over_generic_host(self, monkeypatch):
        monkeypatch.delenv("SSO_IDP_DISCOVERY_URL", raising=False)
        monkeypatch.setenv("DATABRICKS_PILOT_HOST", "pilot.example.com")
        monkeypatch.setenv("DATABRICKS_HOST", "other.example.com")
        url = check_idp_jwks.resolve_discovery_url()
        assert url == (
            "https://pilot.example.com/oidc/.well-known/oauth-authorization-server"
        )

    def test_generic_host_derives_the_discovery_path(self, monkeypatch):
        monkeypatch.delenv("SSO_IDP_DISCOVERY_URL", raising=False)
        monkeypatch.delenv("DATABRICKS_PILOT_HOST", raising=False)
        monkeypatch.setenv("DATABRICKS_HOST", "dbx.example.com")
        url = check_idp_jwks.resolve_discovery_url()
        assert url == (
            "https://dbx.example.com/oidc/.well-known/oauth-authorization-server"
        )

    def test_no_configuration_resolves_to_none(self, monkeypatch):
        monkeypatch.delenv("SSO_IDP_DISCOVERY_URL", raising=False)
        monkeypatch.delenv("DATABRICKS_PILOT_HOST", raising=False)
        monkeypatch.delenv("DATABRICKS_HOST", raising=False)
        assert check_idp_jwks.resolve_discovery_url() is None


class TestMainCapable:
    def test_capable_exits_0_and_reports_the_verdict(self, idp, monkeypatch, capsys):
        monkeypatch.setenv("SSO_IDP_DISCOVERY_URL", idp.discovery_url)
        assert _run() == 0
        out = capsys.readouterr().out
        assert "RESULT: CAPABLE" in out
        assert "JWKS_EXPOSED" in out
        assert "cli-test-rsa" in out
        assert "usable signing keys: 1" in out

    def test_json_shape(self, idp, monkeypatch, capsys):
        monkeypatch.setenv("SSO_IDP_DISCOVERY_URL", idp.discovery_url)
        assert _run("--json") == 0
        payload = json.loads(capsys.readouterr().out)
        assert payload["status"] == "CAPABLE"
        assert payload["report"]["key_count"] == 1
        assert payload["report"]["usable_signing_keys"] == 1
        assert payload["report"]["kty_counts"] == {"RSA": 1}
        assert payload["report"]["keys"][0]["kid"] == "cli-test-rsa"


class TestMainNotCapable:
    def test_empty_jwks_is_not_capable(self, monkeypatch, capsys):
        idp = _ScriptedIdP(jwks={"keys": []})
        try:
            monkeypatch.setenv("SSO_IDP_DISCOVERY_URL", idp.discovery_url)
            assert _run() == 1
            out = capsys.readouterr().out
            assert "RESULT: NOT_CAPABLE" in out
            assert "JWKS_NOT_EXPOSED" in out
            assert "no keys" in out
        finally:
            idp.close()

    def test_unreachable_idp_reports_the_transport_class(self, monkeypatch, capsys):
        monkeypatch.setenv(
            "SSO_IDP_DISCOVERY_URL",
            "http://127.0.0.1:1/oidc/.well-known/oauth-authorization-server",
        )
        assert _run() == 1
        out = capsys.readouterr().out
        assert "RESULT: NOT_CAPABLE" in out
        assert "ConnectError" in out

    def test_failures_never_carry_the_response_body(self, monkeypatch, capsys):
        idp = _ScriptedIdP(
            jwks_status=401, jwks_raw_body=b'{"error": "secret-token-abc123"}'
        )
        try:
            monkeypatch.setenv("SSO_IDP_DISCOVERY_URL", idp.discovery_url)
            assert _run() == 1
            out = capsys.readouterr().out
            assert "secret-token-abc123" not in out
            assert "HTTP 401" in out
        finally:
            idp.close()


class TestMainSkip:
    def test_no_idp_wired_skips_gracefully(self, monkeypatch, capsys):
        monkeypatch.delenv("SSO_IDP_DISCOVERY_URL", raising=False)
        monkeypatch.delenv("DATABRICKS_PILOT_HOST", raising=False)
        monkeypatch.delenv("DATABRICKS_HOST", raising=False)
        monkeypatch.delenv("CI", raising=False)
        assert _run() == 0
        out = capsys.readouterr().out
        assert "RESULT: SKIP" in out

    def test_strict_turns_skip_into_failure(self, monkeypatch, capsys):
        monkeypatch.delenv("SSO_IDP_DISCOVERY_URL", raising=False)
        monkeypatch.delenv("DATABRICKS_PILOT_HOST", raising=False)
        monkeypatch.delenv("DATABRICKS_HOST", raising=False)
        monkeypatch.delenv("CI", raising=False)
        assert _run("--strict") == 1
        out = capsys.readouterr().out
        assert "RESULT: SKIP" in out

    def test_ci_raises_instead_of_skipping(self, monkeypatch):
        monkeypatch.delenv("SSO_IDP_DISCOVERY_URL", raising=False)
        monkeypatch.delenv("DATABRICKS_PILOT_HOST", raising=False)
        monkeypatch.delenv("DATABRICKS_HOST", raising=False)
        monkeypatch.setenv("CI", "true")
