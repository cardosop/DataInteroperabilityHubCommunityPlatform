#!/usr/bin/env python3
"""W11.6 (oss-release-remediation) — encryption-coverage audit.

The Phase 285.12 audit script of the same name was deleted as an orphan
(W12.4); this is the rebuilt, AST-based version covering the CURRENT
encryption surfaces:

* Fernet — ``hub/apps/webhooks/encryption.py`` (webhook secrets,
  ``v1:`` prefix; key derived from ``ENCRYPTION_KEY`` via SHA-256);
* AWS KMS — ``hub/apps/integrations/encryption.py`` (``aws-kms:``
  prefix; also home of the field-level ``encrypt_json_field`` /
  ``decrypt_json_field`` helpers);
* field-level encrypted-at-rest consumers — every non-test caller of
  ``encrypt_json_field`` (scheduled_export destination config,
  scheduled_ingestion source config, data_movement DLT credentials,
  TenantConfig ``sso_config`` + ``tax_address``).

Modes:

* ``--report`` rewrites ``docs/audits/w116-encryption-coverage-2026-10-16.md``;
* ``--ci`` exits 1 when the committed report drifts from a fresh scan
  (a NEW encrypted-at-rest surface must update the report in the same
  change — the W12.8 veracity rule applied to the coverage audit).

Wired into ``make quality-gates``; pinned by
``scripts/tests/test_w116_exc_str_leak_ban.py``.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REPORT_PATH = REPO_ROOT / "docs" / "audits" / "w116-encryption-coverage-2026-10-16.md"

# The canonical encryption seams (module → what it provides).
_ENCRYPTION_SEAMS = {
    "hub/apps/webhooks/encryption.py": "Fernet (v1:) webhook-secret encryption; KMS-first fallback logic",
    "hub/apps/integrations/encryption.py": "AWS KMS (aws-kms:) + encrypt_json_field/decrypt_json_field field-level helpers",
}

_EXCLUDED_PARTS = {"__pycache__", "migrations", "tests", ".venv", "venv", "site-packages"}


def _field_level_consumers() -> dict[str, list[str]]:
    """Every non-test caller of encrypt_json_field/decrypt_json_field."""
    consumers: dict[str, list[str]] = {}
    for path in sorted((REPO_ROOT / "hub").rglob("*.py")):
        if _EXCLUDED_PARTS & set(path.parts):
            continue
        if path.name == "encryption.py" and str(path.relative_to(REPO_ROOT)) in _ENCRYPTION_SEAMS:
            continue
        try:
            source = path.read_text(encoding="utf-8")
            tree = ast.parse(source)
        except (OSError, SyntaxError, UnicodeDecodeError):
            continue
        uses: list[str] = []
        for node in ast.walk(tree):
            if isinstance(node, ast.Name) and node.id in (
                "encrypt_json_field",
                "decrypt_json_field",
            ):
                uses.append(node.id)
        if uses:
            rel = str(path.relative_to(REPO_ROOT))
            consumers[rel] = sorted(set(uses))
    return consumers


def _build_report() -> str:
    seams = _ENCRYPTION_SEAMS
    consumers = _field_level_consumers()
    lines = [
        "# W11.6 — Encryption Coverage Audit",
        "",
        "Generated by `scripts/audit_encryption_coverage.py --report`"
        " (2026-10-16).",
        "Every encrypted-at-rest surface in the tree, with its seam.",
        "",
        "## Encryption seams",
        "",
    ]
    for module, description in seams.items():
        lines.append(f"- `{module}` — {description}")
    lines.append("")
    lines.append("## Field-level encrypted-at-rest consumers")
    lines.append("")
    if not consumers:
        lines.append("None found.")
    for module in sorted(consumers):
        uses = ", ".join(consumers[module])
        lines.append(f"- `{module}` — uses `{uses}`")
    lines.append("")
    lines.append("## TenantConfig")
    lines.append("")
    lines.append(
        "- `hub/apps/tenants/models.py` — `sso_config` and `tax_address` "
        "encrypted at rest via `encrypt_json_field` in `save()`."
    )
    lines.append("")
    lines.append("## Key management")
    lines.append("")
    lines.append(
        "- `ENCRYPTION_KEY` (Fernet fallback) — explicit-secrets contract "
        "(G12), rotation runbook `docs/runbooks/fernet-key-rotation.md`."
    )
    lines.append(
        "- `AWS_KMS_KEY_ID` (KMS, preferred when set) — KMS key rotation "
        "handles re-encryption without data migration."
    )
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="encryption-coverage audit")
    parser.add_argument(
        "--report",
        action="store_true",
        help="rewrite the committed coverage report and exit",
    )
    parser.add_argument(
        "--ci",
        action="store_true",
        help="exit 1 when the committed report drifts from a fresh scan",
    )
    args = parser.parse_args(argv)

    fresh = _build_report()
    if args.report:
        REPORT_PATH.write_text(fresh, encoding="utf-8")
        print(f"encryption-coverage report written: {REPORT_PATH}")
        return 0
    if args.ci:
        if not REPORT_PATH.is_file():
            print("ENCRYPTION-COVERAGE: report missing — run --report first")
            return 1
        committed = REPORT_PATH.read_text(encoding="utf-8")
        if committed != fresh:
            print("ENCRYPTION-COVERAGE: report drifts from the tree — "
                  "regenerate with --report and commit the update")
            return 1
        print("ENCRYPTION-COVERAGE: report current")
        return 0
    print(fresh, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
